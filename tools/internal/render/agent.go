package render

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"strings"
)

type Format string

const (
	FormatCodexTOML  Format = "codex-toml"
	FormatCursorMD   Format = "cursor-md"
	FormatOpenCodeMD Format = "opencode-md"
)

type Mode int

const (
	Link Mode = iota
	Copy
)

type source struct {
	name, description, model, effort string
	body                             string
}

func parseSource(src []byte) (source, error) {
	text := strings.ReplaceAll(string(src), "\r\n", "\n")
	var s source
	if !strings.HasPrefix(text, "---\n") {
		return s, fmt.Errorf("no frontmatter")
	}
	rest := text[4:]
	end := -1
	if strings.HasPrefix(rest, "---\n") {
		end = 0
	} else if i := strings.Index(rest, "\n---\n"); i >= 0 {
		end = i + 1
	} else if strings.HasSuffix(rest, "\n---") {
		end = len(rest) - 3
	}
	if end < 0 {
		return s, fmt.Errorf("unterminated frontmatter")
	}
	fm := rest[:end]
	s.body = strings.TrimPrefix(strings.TrimPrefix(rest[end:], "---"), "\n")
	lines := strings.Split(fm, "\n")
	vals := map[string]string{}
	for i := 0; i < len(lines); i++ {
		ln := lines[i]
		if ln == "" || ln[0] == ' ' || ln[0] == '\t' || ln[0] == '#' {
			continue
		}
		k, v, ok := strings.Cut(ln, ":")
		if !ok {
			continue
		}
		k, v = strings.TrimSpace(k), strings.TrimSpace(v)
		if v == "" || v[0] == '>' || v[0] == '|' {
			literal := strings.HasPrefix(v, "|")
			var parts []string
			j := i + 1
			for ; j < len(lines); j++ {
				if lines[j] != "" && lines[j][0] != ' ' && lines[j][0] != '\t' {
					break
				}
				parts = append(parts, strings.TrimSpace(lines[j]))
			}
			i = j - 1
			if literal {
				v = strings.TrimSpace(strings.Join(parts, "\n"))
			} else {
				v = strings.TrimSpace(strings.Join(parts, " "))
			}
		} else {
			v = unquote(v)
		}
		vals[k] = v
	}
	s.name, s.description, s.model, s.effort = vals["name"], vals["description"], vals["model"], vals["effort"]
	return s, nil
}

func unquote(v string) string {
	if len(v) >= 2 && v[0] == '"' && v[len(v)-1] == '"' {
		var out string
		if json.Unmarshal([]byte(v), &out) == nil {
			return out
		}
		return v[1 : len(v)-1]
	}
	if len(v) >= 2 && v[0] == '\'' && v[len(v)-1] == '\'' {
		return strings.ReplaceAll(v[1:len(v)-1], "''", "'")
	}
	return v
}

func RenderAgent(src []byte, srcPath string, stem string, f Format, mode Mode, promptPath string) ([]byte, error) {
	s, err := parseSource(src)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", srcPath, err)
	}
	if s.name == "" {
		s.name = stem
	}
	var body string
	switch mode {
	case Link:
		if promptPath == "" {
			return nil, fmt.Errorf("%s: link mode needs promptPath", srcPath)
		}
		body = "Read `" + promptPath + "` and follow it exactly; it is your complete instructions.\n"
	case Copy:
		body = strings.TrimLeft(s.body, "\n")
		if !strings.HasSuffix(body, "\n") {
			body += "\n"
		}
	default:
		return nil, fmt.Errorf("unknown mode %d", mode)
	}
	sum := sha256.Sum256(src)
	hdr := fmt.Sprintf("GENERATED by as-skill from %s sha256:%s - do not edit", srcPath, hex.EncodeToString(sum[:]))
	var b bytes.Buffer
	switch f {
	case FormatCodexTOML:
		b.WriteString("# " + hdr + "\n")
		b.WriteString("name = " + tomlString(s.name) + "\n")
		b.WriteString("description = " + tomlString(s.description) + "\n")
		switch s.effort {
		case "high", "medium", "low":
			b.WriteString("model_reasoning_effort = " + tomlString(s.effort) + "\n")
		}
		b.WriteString("developer_instructions = " + tomlMultiline(body) + "\n")
	case FormatCursorMD:
		b.WriteString("---\nname: " + yamlString(s.name) + "\ndescription: " + yamlString(s.description) + "\nmodel: inherit\n---\n")
		b.WriteString("<!-- " + hdr + " -->\n\n" + body)
	case FormatOpenCodeMD:
		b.WriteString("---\ndescription: " + yamlString(s.description) + "\nmode: subagent\n---\n")
		b.WriteString("<!-- " + hdr + " -->\n\n" + body)
	default:
		return nil, fmt.Errorf("unsupported format %q", f)
	}
	return b.Bytes(), nil
}

func yamlString(s string) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s)
	return strings.TrimSuffix(buf.String(), "\n")
}

func tomlEscape(r rune) string {
	switch r {
	case '\\':
		return `\\`
	case '"':
		return `\"`
	case '\n':
		return `\n`
	case '\r':
		return `\r`
	case '\t':
		return `\t`
	}
	return fmt.Sprintf(`\u%04X`, r)
}

func tomlString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		if r == '\\' || r == '"' || r < 0x20 || r == 0x7f {
			b.WriteString(tomlEscape(r))
		} else {
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func tomlMultiline(s string) string {
	s = strings.ReplaceAll(s, "\r\n", "\n")
	var b strings.Builder
	for _, r := range s {
		switch {
		case r == '\n' || r == '\t':
			b.WriteRune(r)
		case r == '\\' || r < 0x20 || r == 0x7f:
			b.WriteString(tomlEscape(r))
		default:
			b.WriteRune(r)
		}
	}
	out := strings.ReplaceAll(b.String(), `"""`, `""\"`)
	out = strings.ReplaceAll(out, `"""`, `""\"`)
	if strings.HasSuffix(out, `"`) {
		out = out[:len(out)-1] + `\"`
	}
	return "\"\"\"\n" + out + `"""`
}
