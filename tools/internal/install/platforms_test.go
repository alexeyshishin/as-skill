func TestPlatformInstallsAreIdempotent(t *testing.T) {
	for _, mode := range []string{"link", "copy"} {
		t.Run(mode, func(t *testing.T) {
			reg, root := platHarness(t)
			project := t.TempDir()
			lock := &lockfile.Lockfile{}
			all := []platform.ID{platform.Claude, platform.Codex, platform.Cursor, platform.OpenCode}
			if err := newInst(root, project, mode, lock, all...).InstallDomain(reg, "alpha", true); err != nil {
				t.Fatal(err)
			}
			first, n := treeDump(t, project), len(lock.Entries)
			if err := newInst(root, project, mode, lock, all...).InstallDomain(reg, "alpha", true); err != nil {
				t.Fatal(err)
			}
			if second := treeDump(t, project); first != second {
				t.Fatalf("reinstall changed tree:\n%s\n---\n%s", first, second)
			}
			if len(lock.Entries) != n {
				t.Fatalf("lock entries %d -> %d", n, len(lock.Entries))
			}
		})
	}
}

