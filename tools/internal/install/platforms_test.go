func exists(p string) bool {
	_, err := os.Lstat(p)
	return err == nil
}

func readStr(t *testing.T, p string) string {
	t.Helper()
	b, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func treeDump(t *testing.T, root string) string {
	t.Helper()
	var b strings.Builder
	_ = filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		r, _ := filepath.Rel(root, p)
		if r == "." || r == filepath.Join(".claude", "skills-lock.json") {
			return nil
		}
		if d.Type()&fs.ModeSymlink != 0 {
			tg, _ := os.Readlink(p)
			b.WriteString("L " + r + " -> " + tg + "\n")
		} else if !d.IsDir() {
			b.WriteString("F " + r + "\n" + readStr(t, p) + "\n")
		}
		return nil
	})
	return b.String()
}

